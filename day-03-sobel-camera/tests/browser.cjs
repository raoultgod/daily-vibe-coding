const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:chromium.executablePath(),args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.TEST_URL || 'http://localhost:8033');
 assert.equal(await page.locator('#output').evaluate(c=>getComputedStyle(c).visibility),'hidden','empty state shows the grid, not a black canvas');
 assert.equal(await page.locator('.brand-icon svg').count(),1,'brand icon does not depend on installed glyphs');
 await page.getByRole('button',{name:'데모 체험'}).click();
 await page.waitForFunction(()=>document.querySelector('#fps').textContent !== '—');
 assert.ok(await page.locator('#output').evaluate(c=>c.width>0));
 const first=await page.locator('#output').evaluate(c=>c.toDataURL());
 await page.waitForTimeout(300);
 assert.notEqual(await page.locator('#output').evaluate(c=>c.toDataURL()),first,'demo animates');
 await page.getByRole('button',{name:'원본',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'원본',exact:true}).getAttribute('aria-pressed'),'true');
 await page.getByRole('button',{name:'비교',exact:true}).click();
 await page.locator('#intensity').fill('2.5');
 assert.equal(await page.locator('#intensity-value').textContent(),'2.5×');
 await page.getByLabel('좌우 반전').check();
 const downloadEvent=page.waitForEvent('download');
 await page.getByRole('button',{name:'PNG 저장'}).click();
 assert.match((await downloadEvent).suggestedFilename(),/\.png$/);
 await page.getByRole('button',{name:'정지',exact:true}).click();
 assert.equal(await page.locator('#fps').textContent(),'—');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'no mobile overflow');
 await page.screenshot({path:'tests/mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: animated demo, FPS, mode controls, intensity, mirror, PNG download, stop, mobile layout, no page errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
